// Downloads real market logos once into /public/logos/ (served from 'self', so
// no runtime third-party image requests — CSP img-src 'self' stays intact), and
// writes a manifest the <MarketLogo> component reads. Sources, in order:
//   1. SoDEX's own token art  https://sodex.com/assets/img/tokens/{coin}.png
//   2. cryptocurrency-icons   (jsDelivr) for crypto SoDEX doesn't ship
// Anything neither source has falls to a generated monogram in the component.
//
//   node scripts/fetch-logos.mjs
import { writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "public", "logos");
const manifestPath = join(root, "src", "lib", "market-logos-data.ts");

// Full SoDEX mainnet base-coin set (from /markets/symbols).
const COINS =
  "1000BONK 1000PEPE 1000SHIB AAPL AAVE ADA AMD AMZN APT ARB ASTER AVAX AXS BASED BCH BERA BIANRENSHENG BNB BRENTOIL BREV BTC CASHCAT CHZ CL COIN COPPER CRCL CRWD CRWV CXMT DASH DOGE DRAM ENA ETC ETH EWY FARTCOIN FIL GOOGL HBAR HOOD HYPE INTC KIOXIA KORU LINK LIT LITE LTC MCD META MINIMAX MON MORPHO MRNA MRVL MSFT MSTR MU NATGAS NBIS NEAR NIULAI NKE NVDA ONDO OP ORCL PENGU PLTR PONS PUMP QNT SAMSUNG SILVER SKHX SKHY SMCI SNDK SOL SOSO SPCX SUI TAO TON TRUMP TRX TSLA TSM UNI UNITREE US500 USTECH100 VIRTUAL WIF WLD WLFI XAUt XLM XMR XPL XRP ZEC ZHIPU".split(
    " ",
  );

const SODEX = (c) => `https://sodex.com/assets/img/tokens/${c.toLowerCase()}.png`;
const CCI = (c) =>
  `https://cdn.jsdelivr.net/npm/cryptocurrency-icons@0.18.1/svg/color/${c.toLowerCase()}.svg`;
const COINCAP = (c) =>
  `https://assets.coincap.io/assets/icons/${c.toLowerCase()}@2x.png`;

async function grab(url) {
  try {
    const r = await fetch(url);
    if (!r.ok) return null;
    const buf = Buffer.from(await r.arrayBuffer());
    if (buf.length < 100) return null; // guard against tiny error bodies
    return buf;
  } catch {
    return null;
  }
}

await mkdir(outDir, { recursive: true });
const manifest = {}; // COIN -> "png" | "svg"
let sodex = 0,
  cci = 0,
  coincap = 0;

for (const c of COINS) {
  const key = c.toUpperCase();
  let buf = await grab(SODEX(c));
  if (buf) {
    await writeFile(join(outDir, `${c.toLowerCase()}.png`), buf);
    manifest[key] = "png";
    sodex++;
    continue;
  }
  buf = await grab(CCI(c));
  if (buf) {
    await writeFile(join(outDir, `${c.toLowerCase()}.svg`), buf);
    manifest[key] = "svg";
    cci++;
    continue;
  }
  buf = await grab(COINCAP(c));
  if (buf) {
    await writeFile(join(outDir, `${c.toLowerCase()}.png`), buf);
    manifest[key] = "png";
    coincap++;
    continue;
  }
  // no real logo — the component draws a monogram
}

const have = Object.keys(manifest).sort();
const missing = COINS.filter((c) => !manifest[c.toUpperCase()]).sort();

const ts = `// AUTO-GENERATED by scripts/fetch-logos.mjs — do not edit by hand.
// Maps a base coin (UPPERCASE) to its logo file extension in /public/logos/.
// ${have.length}/${COINS.length} SoDEX markets have a real logo; the rest render a monogram.
export const LOGO_EXT: Record<string, "png" | "svg"> = ${JSON.stringify(
  manifest,
  null,
  2,
)};
`;
await writeFile(manifestPath, ts);

console.log(`SoDEX logos:  ${sodex}`);
console.log(`crypto-icons: ${cci}`);
console.log(`coincap:      ${coincap}`);
console.log(`TOTAL real:   ${have.length}/${COINS.length}`);
console.log(`monogram:     ${missing.length}  (${missing.join(" ")})`);
